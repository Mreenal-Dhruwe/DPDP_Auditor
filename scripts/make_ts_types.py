"""Write frontend/src/types/contract.ts from the Pydantic models:

    python -m scripts.make_ts_types

The Finding / Report contract lives in scanner/models.py and the API responses in
backend/jobs.py. This script turns their JSON Schema into TypeScript, so the frontend can
never drift from the backend: tests/test_ts_types.py fails while the file is out of date.

Only the JSON Schema features Pydantic produces for these models are handled: objects,
$ref, string enums (Literal), arrays, dicts (additionalProperties), anyOf with null.
Severity, Confidence and Scope keep their names instead of being repeated inline.
"""

import json
from typing import get_args

from pydantic.json_schema import models_json_schema

from backend.jobs import ScanStarted, ScanStatus, Source, Status
from scanner.config import PROJECT_ROOT
from scanner.models import DISCLAIMER, Confidence, Report, Scope, Severity

OUT = PROJECT_ROOT / "frontend" / "src" / "types" / "contract.ts"
MODELS = [Report, ScanStatus, ScanStarted]
# Literal types shown by name: a schema enum with exactly these values becomes the alias.
ALIASES = {"Severity": Severity, "Confidence": Confidence, "Scope": Scope, "ScanState": Status, "ScanSource": Source}
NAMED = {tuple(get_args(t)): name for name, t in ALIASES.items()}
SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        values = tuple(schema["enum"])
        return NAMED.get(values) or " | ".join(json.dumps(v) for v in values)
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        parts = [ts_type(s) for s in schema["anyOf"]]
        return " | ".join(dict.fromkeys(p for p in parts if p != "null")) + (" | null" if "null" in parts else "")
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        return f"{item}[]" if item.isidentifier() else f"({item})[]"
    if kind == "object":
        value = ts_type(schema["additionalProperties"]) if isinstance(schema.get("additionalProperties"), dict) else "unknown"
        key = ts_type(schema["propertyNames"]) if "propertyNames" in schema else "string"
        return f"Record<{key}, {value}>"
    if kind in SCALARS:
        return SCALARS[kind]
    return "unknown"


def doc(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    lines = [" ".join(line.split()) for line in text.strip().splitlines()]
    return [f"{indent}/**"] + [f"{indent} * {line}".rstrip() for line in lines] + [f"{indent} */"]


def interface(name: str, schema: dict) -> list[str]:
    required = set(schema.get("required", []))
    out = doc(schema.get("description")) + [f"export interface {name} {{"]
    for field, prop in schema["properties"].items():
        optional = "" if field in required else "?"
        out += doc(prop.get("description"), "  ")
        out.append(f"  {field}{optional}: {ts_type(prop)};")
    return out + ["}"]


def render() -> str:
    _, schema = models_json_schema([(m, "serialization") for m in MODELS], ref_template="#/$defs/{model}")
    defs = schema["$defs"]
    lines = [
        "// Generated by scripts/make_ts_types.py from scanner/models.py and backend/jobs.py.",
        "// Do not edit: change the Pydantic models, then run `python -m scripts.make_ts_types`.",
        "",
    ]
    for name, t in ALIASES.items():
        lines.append(f"export type {name} = {' | '.join(json.dumps(v) for v in get_args(t))};")
    lines += [
        "",
        "/** Most severe first, the order used everywhere in the UI. */",
        f"export const SEVERITIES = {json.dumps(list(get_args(Severity)))} as const satisfies readonly Severity[];",
        f"export const CONFIDENCES = {json.dumps(list(get_args(Confidence)))} as const satisfies readonly Confidence[];",
        f"export const DISCLAIMER = {json.dumps(DISCLAIMER)};",
    ]
    for name in sorted(defs):
        lines += ["", *interface(name, defs[name])]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(PROJECT_ROOT).as_posix()}")


if __name__ == "__main__":
    main()
